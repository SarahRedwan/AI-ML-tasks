"""##4. Text Chunking
We split each public service FAQ into text chunks using a sliding-window approach with configurable overlap. The overlap helps preserve context between adjacent chunks.
"""

def chunk_text(
    text: str,
    chunk_size: int = 200,
    chunk_overlap: int = 40
) -> List[str]:
    """Splits text into word chunks with overlapping context."""

    words = text.split()

    if chunk_size <= 0:
        raise ValueError("chunk_size must be greater than zero")

    if chunk_overlap < 0 or chunk_overlap >= chunk_size:
        raise ValueError(
            "chunk_overlap must be between 0 and chunk_size - 1"
        )

    if len(words) <= chunk_size:
        return [text]

    chunks = []
    start = 0

    while start < len(words):
        end = start + chunk_size
        chunks.append(" ".join(words[start:end]))

        if end >= len(words):
            break

        start += chunk_size - chunk_overlap

    return chunks


def prepare_chunks(
    df: pd.DataFrame,
    chunk_size: int = 150,
    chunk_overlap: int = 30
) -> List[Dict[str, Any]]:
    """Generates indexed chunks enriched with metadata."""

    chunks_list = []

    for _, row in df.iterrows():
        combined_text = (
            f"Category: {row['category']} | "
            f"Question: {row['question']} | "
            f"Answer: {row['answer']}"
        )

        text_chunks = chunk_text(
            combined_text,
            chunk_size=chunk_size,
            chunk_overlap=chunk_overlap
        )

        for idx, chunk in enumerate(text_chunks):
            chunks_list.append({
                "chunk_id": f"service_{row['id']}_chunk_{idx}",
                "faq_id": int(row["id"]),
                "category": row["category"],
                "question": row["question"],
                "text": chunk,
                "char_length": len(chunk),
                "word_count": len(chunk.split())
            })

    return chunks_list


